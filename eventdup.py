"""같은 사건이 여러 매체로 들어와 여러 번 발행되는 것을 코드로 막는다.

## 왜 모델만으로는 안 되는가

중복 판정은 프롬프트(`prompts_ko` '이미 발행된 글과 비교')가 이미 하고 있다.
그런데 실측(2026-09-28)에서 CCIP 2.0 발표 **한 건이 여섯 번** 나갔다.

    12:44 체인링크, CCIP 2.0 출시로 기업용 맞춤형 보안 검사 기능 도입   (CoinDesk)
    15:20 체인링크, 보안 통제 강화한 CCIP 2.0 출시                     (CoinDesk 규제)
    17:25 체인링크, 기업 맞춤형 보안 검증 지원하는 CCIP 2 출시          (ChainCatcher)
    18:13 체인링크, 금융기관용 브릿지 보안 검증 기능 CCIP 2.0 도입      (Decrypt)
    19:02 체인링크, 커스텀 검증기 도입한 CCIP 2.0 출시                  (The Defiant)

원인이 둘인데 **둘 다 모델이 어쩔 수 없는 것**이다.

 1. **한 회차 안에서는 서로를 못 본다.** `main.process_items` 는 발행 이력을
    요약 **전에 한 번** 읽어 그 묶음 전체에 같은 목록을 넘긴다. 회당 최대 18건을
    동시에 요약하므로, 같은 묶음에 들어온 형제 기사는 서로의 존재를 모른다.
 2. **이력 창이 너무 좁았다.** `Store.recent_for_dedup` 의 기본이 10건이었다.
    하루 300건(시간당 12건)을 내보내는 채널에서 10건은 한 회차도 못 덮는다.

2번은 창을 넓혀 고쳤다(`main.DEDUP_RECENT`). 1번은 창을 넓혀도 안 된다 —
아직 발행되지 않은 형제는 이력에 없다. 그래서 이 모듈이 필요하다.

## 판정 방법 — 흔한 말이 아니라 드문 말을 본다

모델을 부르지 않는다(한도를 쓰지 않는다). 헤드라인만으로 본다.

처음엔 낱말 겹침 비율(자카드)로 했는데 **재현율이 28% 밖에 안 됐다.**
같은 사건이어도 매체마다 수식어가 달라 겹침 비율이 0.25 근처로 깔린다.

    A 체인링크, CCIP 2.0 출시로 기업용 맞춤형 보안 검사 기능 도입
    B 체인링크, 보안 통제 강화한 CCIP 2.0 출시
    → 겹치는 낱말은 {체인링크, CCIP, 보안} 셋뿐 (자카드 0.25)

거꾸로 **흔한 말만 겹쳐도 비율은 높게 나온다.** 이쪽이 오탐이 된다.

    A 게이트아이오, 밈 코인 ALLINU 무기한 선물 상장
    B OKX, AKE 무기한 선물 상장
    → {무기한, 선물, 상장} 이 겹쳐 자카드 0.75 — 완전히 다른 사건이다

즉 **겹치는 낱말의 개수가 아니라 희귀도**가 신호다. 'CCIP'·'파이어블록스'가
겹치면 같은 사건이고, '선물'·'상장'이 겹치는 건 아무 뜻이 없다.

그래서 발행 이력에서 낱말별 문서빈도(DF)를 세어 IDF 가중 코사인을 쓴다.
드문 낱말이 겹칠수록 점수가 올라간다. 코퍼스는 `set_corpus()` 로 넣는다
(`main` 이 기동 때 발행 이력으로 채운다). 안 넣으면 모든 낱말을 같은 무게로
보므로 판정이 둔해진다 — 동작은 하지만 재현율이 떨어진다.

표기가 흔들리면 이 판정이 그대로 깨지므로 `glossary.canonicalize` 를 먼저 거친다.
'글램스터담' 과 '그램스타덤' 은 사전 없이는 다른 낱말이고, 모델이 이름을 영문으로
남겨 둔 글('카카오페이, Ondo Finance 및 Dinari와…')은 한글로 쓴 같은 사건
기사와 한 낱말도 겹치지 않는다.

## 판정이 틀렸을 때

애매하면 **발행하는 쪽**으로 둔다. 뉴스 채널에서 놓치는 쪽이 중복보다 나쁘다는
것이 이 봇의 기존 판단이다(RULES 10-4). 문턱은 그 전제로 맞췄다 —
`tools/eval_dedup.py` 가 실제 발행 이력으로 재현/오탐을 측정한다.
"""

import math
import re

import glossary

# IDF 가중 코사인이 이 선을 넘으면 같은 사건으로 본다.
#
# 0.42 는 **오탐이 0 이 되는 가장 낮은 값**이다(tools/eval_dedup.py 실측).
# 0.40 으로 내리면 재현이 76%→84% 로 오르지만 서로 다른 뉴스가 묶인다.
#
#     미국 XRP 현물 ETF 일간 2619만 달러 순유입
#     미국 비트코인 현물 ETF, 9일간의 순유입세 마감하고 순유출 기록   ← 0.40
#
# 중복 하나 더 나가는 것보다 뉴스 하나 버리는 쪽이 나쁘다(RULES 10-4).
# 그래서 재현을 포기하고 오탐 0 을 택했다. 문턱을 만지면 eval_dedup.py 를 돌릴 것.
SIM_FLOOR = 0.42
# 낱말이 이보다 적은 제목은 판정하지 않는다. 점수가 한두 낱말에 좌우돼 못 믿는다.
MIN_TOKENS = 3

# 상투어(TEMPLATE_WORDS)를 뺀 공유 낱말이 이보다 적으면 같은 사건으로 보지 않는다
# — 점수가 넘더라도.
#
# **문턱만으로는 못 가르는 오탐이 있다.** 짧은 제목 둘이 드문 낱말 두 개를
# 공유하면 코사인이 문턱을 넘는다. 실측된 오탐과 진짜 중복을 나란히 두면
# 갈리는 것은 점수가 아니라 **공유 낱말의 개수**였다.
#
#   0.420  시세(8.1) 실시간(7.7)                             ← 오탐
#          "Pyth Network, 나스닥 실시간 시세 데이터 외부분파사 선정"
#          "X, 실시간 암호화폐 시세 확인 및 거래 연동 기능 도입"
#   0.425  글램스터담(7.2) 차기(7.1) 업그레이드(5.6) 이더리움(4.5)   ← 진짜 중복
#   0.436  지분(6.1) 인수(5.7) 바이낸스(4.3) 달러(3.1)            ← 진짜 중복
#
# 같은 사건을 다룬 두 글은 주체·행위·대상이 모두 겹치므로 셋 이상이 걸린다.
MIN_SHARED = 3

# 이 탭은 코드 판정에서 뺀다 — **틀린 쪽으로 몰려 있기 때문이다.**
#
# 지표 탭(Trading Economics)과 거래소이슈 탭은 글이 전부 같은 틀로 쓰인다.
# "<나라> <월> 제조업 PMI <숫자>", "<거래소>, <토큰> 무기한 선물 상장".
# 그래서 **사건이 다른데 낱말이 겹친다.** 실측된 오탐:
#
#     한국 8월 제조업 PMI 52.3, 예상치 하회
#     말레이시아 8월 제조업 PMI 50.2 기록                     ← 다른 나라 발표
#
#     빗썸, 솔라나 기반 USELESS 원화 마켓 상장
#     업비트, BTC·USDT 마켓에 HEMI 및 USELESS 토큰 상장        ← 다른 거래소 공지
#
# 반대로 서술형 탭(이슈·US Policy 등)에서 0.40 이상으로 걸린 쌍을 표본으로 보면
# 거의 다 진짜 중복이었다(이슈 8/8, US Policy 8/8).
#
# 뺀다고 판정이 아예 없어지는 것은 아니다 — 모델 쪽 중복 판정
# (`prompts_ko` '이미 발행된 글과 비교')은 모든 탭에 그대로 걸린다.
SKIP_CATEGORIES = frozenset({
    "Global Macro", "US Rates", "Korea Rates", "US Equities", "Korea Equities",
    "거래소이슈",
})

_LATIN = re.compile(r"[A-Za-z][A-Za-z0-9]*(?:\.[0-9]+)?")
_HANGUL = re.compile(r"[가-힣]+")
# 조사·어미. 긴 것부터 떼야 '으로는' 이 '는' 으로 잘리지 않는다.
_TAIL = re.compile(
    r"(으로서|으로써|에서는|에서도|에게서|에게도|으로는|이라는|이라도|으로|에서|에게"
    r"|과의|와의|이라|라는|라도|까지|부터|에도|이나|만을|들을|들이|들은|이랑|한테"
    r"|처럼|같이|마다|조차|보다|로써|의|를|을|이|가|은|는|도|로|와|과|에|만|나|서|랑)$"
)

# 아주 흔해 IDF 로도 충분히 눌리지만, 코퍼스가 없을 때(uniform 가중)를 위해
# 명시적으로 빼 둔다. 여기 없는 흔한 말은 IDF 가 알아서 눌러 준다.
STOPWORDS = frozenset("""
출시 도입 추진 검토 발표 공개 협력 체결 확대 지원 적용 예정 완료 시작 가능 관련
위해 통해 기능 사업 계획 전망 분석 보도 확인 강화 개시 대상 기반 신규 최초 공식
밝혔다 전했다 따르면 이번 지난 올해 내년 기준 규모 수준 가운데 대해 대한 위한
중인 중이다 했다 한다 된다 되는 하는 있는 없는 같은 다른 등의
""".split())

# 시황·지표 기사의 틀을 이루는 말. **이것만 겹치면 같은 사건이 아니다.**
#
# STOPWORDS 와 달리 낱말 자체를 버리지는 않는다 — '금리 인하'·'주가 급락'은
# 사건을 설명하는 데 필요한 말이다. 다만 두 글이 **이것만** 공유한다면 그건
# 같은 틀로 쓰인 다른 사건이다(나라만 다른 지표, 회사만 다른 주가).
TEMPLATE_WORDS = frozenset("""
주가 장중 상승 하락 급등 급락 반등 조정 강세 약세 시세 종가 시초가 최고치 최저치
순유입 순유출 유입 유출 거래량 시가총액 미결제약정
금리 기준금리 인상 인하 국채 수익률 물가 인플레이션 인플레이션율 지수 지표
제조업 서비스업 종합 속보치 확정치 예상치 전망치 성장률 실업률
억원 만원 달러 원화 엔화 유로 위안 위안화 파운드 루블 포인트 퍼센트
기록 경신 돌파 회복 규모 발행 공급
""".split())

# 낱말 → 이 낱말이 나온 발행 글 수. set_corpus() 가 채운다.
_DF: dict[str, int] = {}
_N = 0


def tokens(headline: str) -> frozenset[str]:
    """헤드라인 → 판정에 쓸 낱말 집합. 표기 변형은 먼저 표준으로 맞춘다.

    영문 약어(CCIP·DTCC·ETF)는 대문자로 모아 한글 낱말과 같은 자리에 둔다.
    희귀도로 무게를 매기므로 영문/한글을 따로 다룰 이유가 없다.
    """
    text = glossary.canonicalize(headline or "")

    out = {m.group(0).upper() for m in _LATIN.finditer(text)
           if len(m.group(0)) >= 2}
    for run in _HANGUL.findall(text):
        # 붙어 나온 한글 덩어리에서 조사를 뗀다.
        stem = _TAIL.sub("", run)
        # **떼고 나서 1글자가 되면 되돌린다.** 조사처럼 생긴 글자로 끝나는 짧은
        # 낱말을 통째로 잃기 때문이다. 실제 사고: '온도'(Ondo) 에서 '도' 를 떼어
        # '온' 이 됐고 1글자라 버려져, Ondo 기사들이 회사 이름으로 매칭되지 않았다.
        if len(stem) < 2:
            stem = run
        if len(stem) >= 2 and stem not in STOPWORDS:
            out.add(stem)
    return frozenset(out)


def set_corpus(headlines) -> int:
    """발행 이력으로 낱말 희귀도(IDF)를 학습한다. 쓴 글 수를 돌려준다.

    기동 때 한 번만 부르면 된다. 8,600건이 1초 안쪽이다.
    """
    global _N
    _DF.clear()
    n = 0
    for h in headlines:
        n += 1
        for t in tokens(h):
            _DF[t] = _DF.get(t, 0) + 1
    _N = n
    return n


def weight(token: str) -> float:
    """낱말의 무게. 드물수록 크다.

    코퍼스를 안 넣었으면 전부 1.0 — 자카드와 같아져 판정이 둔해진다.
    """
    if not _N:
        return 1.0
    # +1 은 코퍼스에 없던 낱말(새 고유명사)을 가장 무겁게 두기 위한 것이다.
    # 그게 맞다 — 처음 나온 이름이 가장 사건을 특정한다.
    return math.log((_N + 1) / (_DF.get(token, 0) + 1)) + 1.0


def _cosine(a: frozenset[str], b: frozenset[str]) -> float:
    shared = a & b
    if not shared:
        return 0.0
    num = sum(weight(t) ** 2 for t in shared)
    na = math.sqrt(sum(weight(t) ** 2 for t in a))
    nb = math.sqrt(sum(weight(t) ** 2 for t in b))
    return num / (na * nb) if na and nb else 0.0


def same_event(a: str, b: str) -> tuple[bool, float]:
    """두 헤드라인이 같은 사건인가. (판정, 점수)."""
    ta, tb = tokens(a), tokens(b)
    if len(ta) < MIN_TOKENS or len(tb) < MIN_TOKENS:
        return False, 0.0
    # **상투어를 뺀** 공유 낱말로 센다. 시황·지표 기사는 제목이 틀로 쓰여
    # 상투어만으로도 셋이 쉽게 차고, 그러면 점수가 문턱을 넘어간다.
    #
    #   "마이크로스트래티지 주가 장중 5.03% 상승"
    #   "비트디어(Bitdeer) 주가 장중 10%대 상승 기록"
    #   → 공유 {주가, 장중, 상승} 전부 상투어. 서로 다른 회사의 주가 움직임이다.
    #
    #   "중국 인민은행, 23일 홍콩서 600억 위안 규모 중앙은행어음 발행"
    #   "중국 인민은행, 역환매조건부채권 통해 320억 위안 유동성 공급"
    #   → 공유 {중국, 인민은행, 위안} 중 위안은 상투어. 남은 둘은 주체일 뿐이고
    #     사건(어음 발행 / 역레포)은 다르다.
    #
    # 같은 사건이면 주체·행위·대상이 모두 걸리므로 상투어를 빼고도 셋이 남는다.
    shared = (ta & tb) - TEMPLATE_WORDS
    if len(shared) < MIN_SHARED:
        return False, 0.0
    sim = _cosine(ta, tb)
    return sim >= SIM_FLOOR, sim


def skip(category: str) -> bool:
    """이 탭은 코드 판정을 걸지 않는다(`SKIP_CATEGORIES` 참고)."""
    return (category or "") in SKIP_CATEGORIES


def find_covered(headline: str, published) -> tuple[str, float] | None:
    """이미 발행된 헤드라인 중 같은 사건인 것. 없으면 None.

    `published` 는 최근 발행 목록이다. 발행 이력(다른 회차)과 이번 회차에서
    방금 내보낸 것을 **함께** 넘겨야 한다 — 형제 기사는 이력에 아직 없다.
    """
    best: tuple[str, float] | None = None
    for prev in published:
        hit, sim = same_event(headline, prev)
        if hit and (best is None or sim > best[1]):
            best = (prev, sim)
    return best
