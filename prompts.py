def build_reroute_prompt(rows: list) -> str:
    """여러 건을 한 번에 판정시킨다. 건당 호출하면 수십 건에 수십 분이 걸린다."""
    lines = []
    for i, r in enumerate(rows):
        lede = f" | {r['lede']}" if r.get("lede") else ""
        lines.append(f"{i}. [현재: {r.get('category') or '없음'}] {r['headline']}{lede}")
    return "\n".join(lines)


